def dedupe_novelty_summary(a: pd.DataFrame) -> dict[str, Any]:
    usable = ~a[CLEAN].any(axis=1) & a["has_clean_text"]
    u = a[usable]
    groups = u.groupby("dup_group").size()
    out = {
        "usable_articles": int(usable.sum()),
        "representatives": int(u["is_representative"].sum()),
        "duplicate_share": float(1 - u["is_representative"].mean()),
        "group_size_quantiles": groups.quantile([0.5, 0.9, 0.99, 1.0]).to_dict(),
        "novelty_quantiles": u["novelty"].quantile([0.01, 0.1, 0.25, 0.5, 0.75, 0.9]).to_dict(),
        "novelty_is_one_share": float((u["novelty"] == 1.0).mean()),
        "keep": int(a["keep"].sum()),
        "has_clean_text_false_among_clean": int((~a["has_clean_text"] & ~a[CLEAN].any(axis=1)).sum()),
    }
    return out


def novelty_variant_check(a: pd.DataFrame, emb: embed.Embeddings, n_companies: int = 40) -> dict[str, float]:
    """PREREG §6.5 says "articles", the PRD "representatives": compare on 40 random companies (seed 2026)."""
    usable = (~a[CLEAN].any(axis=1) & a["has_clean_text"]).to_numpy()
    sub = a[usable]
    rng = np.random.default_rng(2026)
    picks = rng.choice(np.sort(sub["company_id"].unique()), n_companies, replace=False)
    sub = sub[sub["company_id"].isin(picks)].reset_index(drop=True)
    vecs = emb.matrix_for(sub["id"])
    alt = novelty.pit_novelty(
        sub.assign(is_representative=True), vecs, mask=np.ones(len(sub), bool), window=pd.Timedelta(days=7)
    )
    d = (sub["novelty"] - alt).abs()
    return {
        "articles": len(sub),
        "mean_abs_diff": float(d.mean()),
        "share_diff_gt_0.01": float((d > 0.01).mean()),
        "spearman": float(sub["novelty"].corr(alt, method="spearman")),
    }


def embedding_check(emb: embed.Embeddings, a: pd.DataFrame) -> dict[str, Any]:
    norms = np.linalg.norm(emb.vecs.astype(np.float32), axis=1)
    keep_ids = a.loc[a["keep"], "id"]
    counts = emb.ids.value_counts()
    return {
        "rows": len(emb.ids),
        "dtype": str(emb.vecs.dtype),
        "dim": int(emb.vecs.shape[1]),
        "norm_min": float(norms.min()),
        "norm_max": float(norms.max()),
        "kept_ids_with_exactly_one_row": bool(keep_ids.isin(counts.index).all() and (counts.max() == 1)),
        "ids_unique": bool(emb.ids.is_unique),
    }


def leavers(a: pd.DataFrame) -> pd.DataFrame:
    members = io.read_parquet("snapshot/members_by_session.parquet")
    companies = io.read_parquet("panel/companies.parquet")
    tiers = io.read_parquet("panel/tiers_monthly.parquet", columns=["month", "company_id", "tier"])
    pairs = mapping.member_companies(members, companies)
    sectors = companies.drop_duplicates("company_id").set_index("company_id")["sector"]
    out = coverage.leaver_check(a, pairs, tiers, sectors)
    _csv(out, "leavers_news_rate.csv")
    return out


def diagnostics(a: pd.DataFrame) -> dict[str, Any]:
    """S13: PREREG §14 diagnostics on ≤ 2025-12-31 with the PREREG timing rules."""
    panel = audit.forward_targets(audit.public_targets())
    cov = io.read_parquet(COVERAGE)
    status = audit.news_status(a, panel, cov)
    var = audit.variance_shares(status[(status["session"] >= date(2024, 1, 2))])
    var_year = []
    for yr, g in status[status["session"] >= date(2024, 1, 2)].groupby(
        pd.to_datetime(status["session"]).dt.year
    ):
        v = audit.variance_shares(g)
        v.insert(0, "year", yr)
        var_year.append(v)
    var_year_df = pd.concat(var_year, ignore_index=True)
    k = a[a["keep"]]
    w0 = k[k["session_w0"].notna()]
    td = audit.join_targets(audit.ticker_day(w0, "session_w0"), panel)
    td = td[td["session"] >= date(2024, 1, 2)]
    ic_rows = []
    ar_of = {"z_on": "ar_on", "z_id": "ar_id", "z_cc": "ar_cc"}
    for target in ("z_on", "z_id", "z_cc", "z_next", "z_5d"):
        r = audit.ic_row(td, "sent", (target,))
        fm = audit.fama_macbeth_bp(td, ar_of[target], 5) if target in ar_of else (np.nan, np.nan)
        ic_rows.append(
            {
                "target": target,
                "ticker_days": int(r["ticker_days"]),
                "days": int(r[f"days_{target}"]),
                "mean_daily_ic": r[f"ic_{target}"],
                "nw_t": r[f"t_{target}"],
                "fm_slope_bp_per_unit": fm[0],
                "fm_t": fm[1],
            }
        )
    ic = pd.DataFrame(ic_rows)
    tags = audit.top_tag(w0, "session_w0")
    td_tag = td.merge(tags, on=["company_id", "session"], how="left")
    cont = audit.continuation(td_tag, "tag_type")
    nonews = status[(status["status"] == "no_news") & (status["session"] >= date(2024, 1, 2))].assign(
        tag_type="(no W2 news)"
    )
    cont_nonews = audit.continuation(nonews, "tag_type")
    by_split = []
    for split, g in td.merge(
        panel[["company_id", "session", "split"]].assign(
            session=lambda x: pd.to_datetime(x["session"]).dt.date
        ),
        on=["company_id", "session"],
    ).groupby("split"):
        r = audit.ic_row(g, "sent")
        by_split.append({"split": split, **r})
    for name, df in (
        ("diag_variance_shares.csv", var),
        ("diag_variance_shares_by_year.csv", var_year_df),
        ("diag_sentiment_ic.csv", ic),
        ("diag_continuation_by_tag.csv", pd.concat([cont, cont_nonews])),
        ("diag_sentiment_ic_by_split.csv", pd.DataFrame(by_split)),
    ):
        _csv(df, name)
    return {
        "var": var,
        "var_year": var_year_df,
        "ic": ic,
        "cont": cont,
        "cont_nonews": cont_nonews,
        "by_split": pd.DataFrame(by_split),
    }


def write_diag_md(d: dict[str, Any]) -> None:
    text = f"""# NA-02 re-derived diagnostics (PRD S13; PREREG §14)

These replace the exploratory diagnostics of 2026-10-24 (PREREG §14), which used 2026 data and ignored the
§2.2–2.3 timestamp rules. Here: sessions **2024-01-02 … 2025-12-31** only (public; asserted in code), PREREG
timing (t_avail, W0/W2), cleaned articles (`keep`, PREREG §6.2), S&P 500 members on representative-class rows,
abnormal returns and z-scores from NA-01's panel (market + leave-one-out sector, PREREG §5). Generated by
`scripts/na02_report.py --part final`; tables also in `artifacts/NA-02/diag_*.csv`.

## 1. Overnight vs intraday share of stock-specific variance, by news status

Covered member-days only (PREREG §3.4). `overnight_share` = Σ AR_on² / (Σ AR_on² + Σ AR_id²).
Status: `pre_open_earnings` (a cleaned W0 article tagged earnings_results), `pre_open` (other cleaned W0
news), `intraday_only` (cleaned W2 news but none in W0), `no_news` (no cleaned W2 article).

{md(d["var"], "{:.3f}")}

By year:

{md(d["var_year"], "{:.3f}")}

## 2. Vendor sentiment of W0 news vs returns

Ticker-day mean vendor sentiment (−2…+2) of cleaned W0 articles. Daily cross-sectional Spearman IC (mean,
Newey–West t, 5 lags). `z_next` = z_cc of the next session; `z_5d` = Σ AR_cc over t+1…t+5 / (σ_cc √5).
`fm_slope_bp_per_unit` = mean daily OLS slope of the abnormal return (bp) on sentiment, with its NW t.

{md(d["ic"], "{:.4f}")}

By split (descriptive; the ICs on z_on and z_id):

{md(d["by_split"][["split", "ticker_days", "ic_z_on", "t_z_on", "ic_z_id", "t_z_id"]], "{:.4f}")}

## 3. Continuation after |z_on| > 2, by vendor tag of the day's W0 news

`cont_id` = sign(z_on) · z_id (same-day open→close); `cont_5d` = sign(z_on) · z_5d (t+1…t+5).
Positive = continuation, negative = reversal. t = mean / (sd / √n) across events (not clustered).
The last row is covered member-days without any cleaned W2 news.

{md(pd.concat([d["cont"], d["cont_nonews"]]), "{:.3f}")}
"""
    (OUT / "rederived_diagnostics.md").write_text(text, encoding="utf-8")


def final() -> dict[str, Any]:
    cols = [
        "id",
        "company_id",
        "t_avail",
        "session_w0",
        "session_w2",
        "keep",
        "has_clean_text",
        "dup_group",
        "dup_count",
        "is_representative",
        "novelty",
        "sentiment_direction",
        "tag_type",
        *CLEAN,
    ]
    a = io.read_parquet(ARTICLES, columns=cols)
    emb = embed.read_embeddings()
    out: dict[str, Any] = {"dedupe_novelty": dedupe_novelty_summary(a), "embedding": embedding_check(emb, a)}
    out["novelty_variant"] = novelty_variant_check(a, emb)
    del emb
    cov = io.read_parquet(COVERAGE)
    out["coverage"] = {
        "member_months": len(cov),
        "covered_share": float(cov["covered"].mean()),
        "uncovered_companies": sorted(cov.loc[~cov["covered"], "company_id"].unique().tolist())[:60],
        "by_year": cov.assign(y=cov["month"].str[:4]).groupby("y")["covered"].mean().to_dict(),
    }
    lv = leavers(a)
    out["leavers"] = {
        "n": len(lv),
        "median_ratio": float(lv["ratio"].median()),
        "share_zero_news": float((lv["leaver_rate"] == 0).mean()),
    }
    d = diagnostics(a)
    write_diag_md(d)
    return out


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--part", choices=["stage1", "final"], required=True)
    args = parser.parse_args()
    res = stage1() if args.part == "stage1" else final()
    summary_path = OUT / "summary.json"
    summary = json.loads(summary_path.read_text(encoding="utf-8")) if summary_path.is_file() else {}

    def plain(v: Any) -> Any:
        if isinstance(v, pd.DataFrame):
            return v.to_dict(orient="records")
        if isinstance(v, dict):
            return {str(k): plain(x) for k, x in v.items()}
        if isinstance(v, np.generic):
            return v.item()
        return v

    summary[args.part] = plain({k: v for k, v in res.items() if k not in ("domains",)})
    summary_path.write_text(json.dumps(summary, indent=2, default=str) + "\n", encoding="utf-8")
    print(json.dumps(summary[args.part], indent=1, default=str)[:6000])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

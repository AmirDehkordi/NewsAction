def corpus_precision() -> pd.DataFrame:
    """Precision-class shares of every row of each Data/news file (the ``date`` column only)."""
    rows = []
    for year in load_news_config().load.years:
        d = pq.read_table(ROOT / "Data" / load.news_file(year), columns=["date"]).column("date").to_numpy()
        cls = timeutil.precision_class(d).value_counts(normalize=True)
        rows.append(
            {
                "file": load.news_file(year),
                "rows": len(d),
                **{c: float(cls.get(c, 0.0)) for c in timeutil.PRECISION_CLASSES},
            }
        )
    return pd.DataFrame(rows)


def timing_audit(a: pd.DataFrame) -> dict[str, Any]:
    a = a.assign(year=a["t_avail"].dt.year)
    naive = load.naive_sessions(a["ts_pub_utc"])
    a = pd.concat([a, naive], axis=1)
    corpus = corpus_precision()
    member = a.groupby("year")["precision"].value_counts(normalize=True).unstack(fill_value=0.0).reset_index()
    member.insert(1, "articles", a.groupby("year").size().to_numpy())
    top_dom = a["domain"].value_counts().head(20).index
    by_dom = (
        a[a["domain"].isin(top_dom)]
        .groupby("domain")["precision"]
        .value_counts(normalize=True)
        .unstack(fill_value=0.0)
    )
    by_dom.insert(0, "articles", a[a["domain"].isin(top_dom)].groupby("domain").size())
    by_dom = by_dom.sort_values("articles", ascending=False).reset_index()
    affected = audit.affected_share(a)
    clean = a[~a[CLEAN].any(axis=1)]
    d0 = audit.d0_ticker_day_change(clean)
    panel = audit.public_targets()
    leak = audit.leak_signature(clean, panel)
    for name, df in (
        ("timing_corpus_precision.csv", corpus),
        ("timing_member_precision.csv", member),
        ("timing_precision_by_domain.csv", by_dom),
        ("timing_affected_share.csv", affected),
        ("timing_d0_ticker_days.csv", d0),
        ("timing_leak_signature.csv", leak),
    ):
        _csv(df, name)
    return {
        "corpus": corpus,
        "member": member,
        "by_dom": by_dom,
        "affected": affected,
        "d0": d0,
        "leak": leak,
    }


def write_timing_md(t: dict[str, Any]) -> None:
    leak = t["leak"][
        [
            "rule",
            "cell",
            "value",
            "ticker_days",
            "ic_z_on",
            "t_z_on",
            "ic_z_id",
            "t_z_id",
            "diff_z_id_minus_z_on",
            "t_diff",
            "days_z_on",
        ]
    ].copy()
    leak["leaky_6_4"] = [audit.is_leaky(r) for _, r in leak.iterrows()]
    text = f"""# NA-02 timing audit (PRD S3; PREREG §2.2–2.4)

Generated by `scripts/na02_report.py --part stage1`. Member articles = articles mapped to an S&P 500
member at `session_w2` (2023-07-01 … 2026-07-31 by t_avail). Return statistics use public sessions only
(≤ 2025-12-31).

**Naive rule** = treat the raw stamp `date` as exact (no §2.3 shift). **PREREG rule** =
`timeutil.availability` (date-only → 23:59:59 UTC of that date; hour → +3599 s; minute → +59 s).

## 1. Precision classes, whole corpus (every row of each file; `date` column only)

{md(t["corpus"], "{:.4f}")}

## 2. Precision classes, member articles by t_avail year

{md(t["member"], "{:.4f}")}

## 3. Precision classes, top 20 member domains

{md(t["by_dom"], "{:.3f}")}

## 4. Articles whose session changes under the PREREG rule (affected share, by year and class)

`w0_changed` / `w2_changed`: share of articles whose W0 / W2 session (or W0 membership) differs from
the naive rule.

{md(t["affected"], "{:.4f}")}

## 5. D0 ticker-days (company, session with ≥ 1 cleaned W0 article), naive vs PREREG

`naive_not_in_prereg`: share of naive D0 ticker-days that are not D0 ticker-days under the PREREG rule;
`prereg_not_in_naive`: the reverse; `article_set_changed`: share of ticker-days (union) whose article set
differs.

{md(t["d0"], "{:.4f}")}

## 6. Leak signature (≤ 2025-12-31): vendor sentiment of W0 articles vs z_on and z_id

Daily cross-sectional Spearman IC of the ticker-day mean sentiment (−2…+2) of cleaned W0 articles, by
precision class (`cell = precision`) and pooled (`cell = all`), with Newey–West t (5 lags). A pre-open
signal should predict the gap (z_on) far more than the open→close return (z_id). `leaky_6_4` applies
PREREG §6.4 (IC(z_id) ≥ IC(z_on) with t(IC(z_id)) > 2).

{md(leak, "{:.4f}")}
"""
    (OUT / "timing_audit.md").write_text(text, encoding="utf-8")


def domains(a: pd.DataFrame) -> pd.DataFrame:
    a = a.assign(clean=~a[CLEAN].any(axis=1))
    g = a.groupby("domain").agg(
        articles=("id", "size"),
        clean_share=("clean", "mean"),
        is_13f=("is_13f", "mean"),
        junk_tag=("junk_tag", "mean"),
        after_fact=("after_fact", "mean"),
        vendor_primary=("tag_primary_source", lambda s: s.astype("boolean").fillna(False).mean()),
        source_class_domain=("source_class_domain", "first"),
    )
    g = g.sort_values("articles", ascending=False).reset_index()
    g["cum_share"] = g["articles"].cumsum() / g["articles"].sum()
    top = g.head(100)
    _csv(top, "top_domains.csv")
    return top


def parsing_allowed(a: pd.DataFrame) -> pd.DataFrame:
    """Shares of parsing_allowed True / None / False, member articles with t_avail in 2024-07 … 2026-07."""
    a = a[a["t_avail"] >= pd.Timestamp("2024-07-01", tz="UTC")]
    a = a.assign(
        period=a["t_avail"].dt.strftime("%Y"),
        pa=a["parsing_allowed"].astype("boolean").map({True: "True", False: "False"}).fillna("None"),
        clean=~a[CLEAN].any(axis=1),
    )
    rows = []
    for scope, sub in (("all member articles", a), ("cleaned (pre-dedupe)", a[a["clean"]])):
        for period, g in [("2024-07..2026-07", sub), *sub.groupby("period")]:
            s = g["pa"].value_counts(normalize=True)
            rows.append(
                {
                    "scope": scope,
                    "period": period,
                    "articles": len(g),
                    "True": s.get("True", 0.0),
                    "None": s.get("None", 0.0),
                    "False": s.get("False", 0.0),
                }
            )
    monthly = (
        a.groupby(a["t_avail"].dt.strftime("%Y-%m"))["pa"].value_counts(normalize=True).unstack(fill_value=0)
    )
    _csv(monthly.reset_index().rename(columns={"t_avail": "month"}), "parsing_allowed_monthly.csv")
    out = pd.DataFrame(rows)
    _csv(out, "parsing_allowed_shares.csv")
    return out


def mapping_report() -> dict[str, Any]:
    stats = json.loads((OUT / "mapping_stats.json").read_text(encoding="utf-8"))
    by = stats["by_year"]
    ref = sum(v["reference_member_day"] for v in by.values())
    ok = sum(v["reference_mapped_member"] for v in by.values())
    top = pd.read_csv(OUT / "unmapped_top100.csv").head(30)
    examples = []
    for year in (2025, 2024, 2026, 2023):
        t = pq.read_table(
            ROOT / "Data" / load.news_file(year),
            columns=["ticker", "title"],
            filters=[("ticker", "in", top["ticker"].tolist())],
        ).to_pandas()
        examples.append(t.drop_duplicates("ticker"))
    ex = pd.concat(examples).drop_duplicates("ticker").set_index("ticker")["title"]
    top["example_title"] = top["ticker"].map(ex).fillna("").str.slice(0, 90)
    _csv(top, "unmapped_top30.csv")
    return {
        "mapped_share": ok / ref,
        "reference": ref,
        "mapped": ok,
        "by_year": by,
        "top": top,
        "duplicate_ids_dropped": stats["duplicate_ids_dropped"],
    }


def stage1() -> dict[str, Any]:
    cols = [
        "id",
        "company_id",
        "ts_pub_utc",
        "precision",
        "t_avail",
        "session_w0",
        "session_w2",
        "domain",
        "sentiment_direction",
        "tag_primary_source",
        "parsing_allowed",
        "source_class_domain",
        "after_fact",
        "premarket_talk",
        *CLEAN,
    ]
    a = io.read_parquet(STAGE1, columns=cols)
    out: dict[str, Any] = {}
    out["domains"] = domains(a)
    out["parsing_allowed"] = parsing_allowed(a)
    out["mapping"] = mapping_report()
    t = timing_audit(a)
    write_timing_md(t)
    out["flags_by_year"] = (
        a.assign(year=a["t_avail"].dt.year).groupby("year")[[*CLEAN, "after_fact", "premarket_talk"]].mean()
    )
    _csv(out["flags_by_year"].reset_index(), "flags_by_year.csv")
    return out



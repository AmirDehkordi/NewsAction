"""NA-16: the paper's result numbers as LaTeX macros, the arXiv abstract, and the checks on the sources.

    uv run python -m newsaction.paper.numbers          # write generated/numbers.tex and arxiv/abstract.txt
    uv run python -m newsaction.paper.numbers --check  # fail if either is stale or a source breaks a rule

**Numbers.** Every result number in the manuscript enters through ``\\res{name}``. ``paper/numbers.yaml`` maps
each name to one cell of NA-14's ``artifacts/NA-14/tables/keys.json`` as ``table/key/column@spec``, NA-14's
citation syntax (``figures.keys``); the cell is rendered by ``figures.keys.render`` and written as an ASCII
LaTeX macro. ``\\res`` of a name the registry lacks stops the compile.

**Checks** (``problems``), on ``paper/main.tex`` and ``paper/sections/*.tex``:

- every ``.tex``, ``.bib`` and ``.yaml`` file under ``paper/`` and the arXiv files are ASCII only (arXiv
  compiles with pdflatex);
- every ``\\res`` name is in the registry, and every registry name is used;
- no hard-coded result number: after the macros, references, citations, file names and the phrases of
  ``paper/allowlist.yaml`` (dates, section numbers, design constants, each with its reason) are removed, no
  token with a digit may remain unless an allowlist pattern matches it;
- every sentence of the exploratory section that cites a number says "exploratory" or "post hoc";
- ``arxiv/abstract.txt`` is the abstract in plain text, 180 to 250 words.

Nothing here reads data, calls an API or imports the lock: only the committed NA-14 keys.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Final

import yaml

from newsaction.figures import keys as kz
from newsaction.paths import Layout, resolve_layout

PAPER: Final = "paper"
REGISTRY: Final = f"{PAPER}/numbers.yaml"
ALLOWLIST: Final = f"{PAPER}/allowlist.yaml"
OUTPUT: Final = f"{PAPER}/generated/numbers.tex"
MAIN: Final = f"{PAPER}/main.tex"
SECTIONS: Final = f"{PAPER}/sections"
ABSTRACT_TEX: Final = f"{SECTIONS}/abstract.tex"
EXPLORATORY_TEX: Final = f"{SECTIONS}/exploratory.tex"
ARXIV: Final = "arxiv"
ABSTRACT_TXT: Final = f"{ARXIV}/abstract.txt"
KEYS: Final = "artifacts/NA-14/tables/keys.json"
ABSTRACT_WORDS: Final = (180, 250)

NAME: Final = re.compile(r"^[a-z][a-z0-9-]*$")
RES: Final = re.compile(r"\\res\{([^{}]*)\}")
COMMENT: Final = re.compile(r"(?<!\\)%.*$", re.MULTILINE)

HEADER: Final = (
    "% Generated by `make paper-text` (python -m newsaction.paper.numbers) from paper/numbers.yaml and\n"
    "% artifacts/NA-14/tables/keys.json. Do not edit: change the registry or the tables, then regenerate.\n"
    "\\makeatletter\n"
    "\\DeclareRobustCommand{\\res}[1]{\\@ifundefined{res@#1}"
    "{\\PackageError{numbers}{Unknown result `#1'}{Add it to paper/numbers.yaml and run make paper-text.}}"
    "{\\csname res@#1\\endcsname}}\n"
)
FOOTER: Final = "\\makeatother\n"


# --- rendering ----------------------------------------------------------------------------------------------


def latex_value(text: str) -> str:
    """A rendered cell as ASCII LaTeX that works in text and in math: true minus, escaped percent, a thousands
    comma that math does not space, and math-only symbols wrapped in ``\\ensuremath``."""
    out = (
        text.replace("\u2212", "\\ensuremath{-}")
        .replace("\u221e", "\\ensuremath{\\infty}")
        .replace("%", "\\%")
        .replace("<", "\\ensuremath{<}")
    )
    out = re.sub(r"(?<=\d),(?=\d{3})", "{,}", out)
    if not out.isascii():
        raise ValueError(f"no ASCII LaTeX for {text!r}")
    return out


def plain_value(text: str) -> str:
    """A rendered cell as plain ASCII text (the arXiv abstract field)."""
    out = text.replace("\u2212", "-").replace("\u221e", "infinity")
    if not out.isascii():
        raise ValueError(f"no ASCII text for {text!r}")
    return out


def load_registry(root: Path) -> dict[str, str]:
    """name -> ``table/key/column[@spec]``, in file order; names must be lowercase words joined by hyphens."""
    data = yaml.safe_load((root / REGISTRY).read_text(encoding="utf-8"))
    reg = data.get("numbers") if isinstance(data, dict) else None
    if not isinstance(reg, dict) or not reg:
        raise ValueError(f"{REGISTRY}: expected a non-empty mapping under 'numbers'")
    out: dict[str, str] = {}
    for name, ref in reg.items():
        if not isinstance(name, str) or not NAME.match(name):
            raise ValueError(f"{REGISTRY}: bad name {name!r} (lowercase letters, digits and hyphens)")
        if not isinstance(ref, str) or "/" not in ref:
            raise ValueError(f"{REGISTRY}: {name}: expected 'table/key/column[@spec]', got {ref!r}")
        out[name] = ref
    return out


def values(root: Path) -> dict[str, str]:
    """name -> the cell as NA-14 renders it (Unicode minus, percent sign, thousands separators)."""
    keys = kz.load(root / KEYS)
    return {name: kz.render(ref, keys) for name, ref in load_registry(root).items()}


def numbers_tex(root: Path) -> str:
    """The text of ``paper/generated/numbers.tex``."""
    reg = load_registry(root)
    vals = values(root)
    lines = [HEADER]
    for name in reg:
        lines.append(f"\\@namedef{{res@{name}}}{{{latex_value(vals[name])}}}% {reg[name]}\n")
    lines.append(FOOTER)
    return "".join(lines)


# --- the abstract as plain text -----------------------------------------------------------------------------

_LATEX_TEXT: Final = (
    (re.compile(r"\\&"), "&"),
    (re.compile(r"\\%"), "%"),
    (re.compile(r"~"), " "),
    (re.compile(r"--"), "-"),
    (re.compile(r"``|''"), '"'),
    (re.compile(r"\$([^$]*)\$"), r"\1"),
)


def abstract_text(root: Path) -> str:
    """The abstract (``sections/abstract.tex``) with its macros resolved, as plain ASCII text on one line."""
    vals = values(root)
    tex = COMMENT.sub("", (root / ABSTRACT_TEX).read_text(encoding="utf-8"))
    text = RES.sub(lambda m: plain_value(vals[m.group(1)]), tex)
    for pattern, repl in _LATEX_TEXT:
        text = pattern.sub(repl, text)
    text = " ".join(text.split())
    if "\\" in text or "{" in text or "}" in text:
        raise ValueError(f"{ABSTRACT_TEX}: LaTeX left in the plain-text abstract: {text[:120]!r}")
    return text + "\n"


def words(text: str) -> int:
    return len(text.split())


# --- checks -------------------------------------------------------------------------------------------------


@dataclass(frozen=True)
class Allowlist:
    phrases: tuple[str, ...]
    patterns: tuple[re.Pattern[str], ...]


def load_allowlist(root: Path) -> Allowlist:
    """Phrases (literal text removed before the scan) and token patterns (a full match passes), each listed
    with its reason in ``paper/allowlist.yaml``."""
    data = yaml.safe_load((root / ALLOWLIST).read_text(encoding="utf-8"))
    phrases: list[str] = []
    patterns: list[re.Pattern[str]] = []
    for entry in data.get("phrases", []):
        if not entry.get("why"):
            raise ValueError(f"{ALLOWLIST}: phrase {entry.get('text')!r} has no reason")
        phrases.append(str(entry["text"]))
    for entry in data.get("patterns", []):
        if not entry.get("why"):
            raise ValueError(f"{ALLOWLIST}: pattern {entry.get('re')!r} has no reason")
        patterns.append(re.compile(str(entry["re"])))
    # Longest first, so that a phrase is not cut by a shorter one inside it.
    return Allowlist(tuple(sorted(phrases, key=len, reverse=True)), tuple(patterns))


def tex_sources(root: Path) -> list[Path]:
    """The manuscript's own LaTeX: main.tex and the sections (not the generated macros or NA-14's tables)."""
    return [root / MAIN, *sorted((root / SECTIONS).glob("*.tex"))]


def body(tex: str) -> str:
    """The part of a source that prints: comments dropped, and main.tex from \\begin{document} on."""
    tex = COMMENT.sub("", tex)
    if "\\begin{document}" in tex:
        tex = tex[tex.index("\\begin{document}") :]
    return tex


_DROP: Final = (
    RES,
    re.compile(
        r"\\(?:ref|eqref|label|input|includegraphics|url|bibliography|bibliographystyle)"
        r"(?:\[[^\]]*\])?\{[^{}]*\}"
    ),
    re.compile(r"\\cite[tp]?\*?(?:\[[^\]]*\])*\{[^{}]*\}"),
    re.compile(r"\\(?:begin|end)\{[^{}]*\}(?:\[[^\]]*\])?"),
    re.compile(r"\\setcounter\{[^{}]*\}\{[^{}]*\}"),
    re.compile(r"\\(?:needspace|vspace|hspace)\*?\{[^{}]*\}|\\multicolumn\{\d+\}"),
)
_TOKEN: Final = re.compile(r"[A-Za-z0-9_.,:+\-/^]*\d[A-Za-z0-9_.,:+\-/^]*")
_DISPLAY: Final = re.compile(r"\\begin\{(equation\*?|align\*?)\}(.*?)\\end\{\1\}|\\\[(.*?)\\\]", re.DOTALL)
_INLINE: Final = re.compile(r"\$([^$]*)\$")
# In math, indices and whole-number constants pass (t+20, i,t-1, 1/2, 10:00); a decimal must be an allowlisted
# phrase, and every result enters through \res.
_MATH_OK: Final = re.compile(r"[^.]*")


def _tokens(text: str) -> list[str]:
    text = text.replace("{,}", ",").replace("\\%", "%").replace("~", " ")
    text = re.sub(r"\\[A-Za-z]+", " ", text)  # commands, after the phrases that name them
    text = re.sub(r"[{}$\\]", " ", text)
    toks = (m.group(0).strip(".,:;") for m in _TOKEN.finditer(text))
    return [t for t in toks if any(ch.isdigit() for ch in t)]


def bare_numbers(tex: str, allow: Allowlist) -> list[str]:
    """The tokens with a digit that are neither a macro, a reference nor an allowlisted phrase or pattern.
    Math
    (inline and displayed) may hold whole numbers, its indices and constants; text may not."""
    text = " ".join(body(tex).split())
    for phrase in allow.phrases:
        text = text.replace(" ".join(phrase.split()), " ")
    text = text.replace("\\$", " USD ")  # an escaped dollar sign is not a math delimiter
    out: list[str] = []
    math: list[str] = []

    def keep_math(m: re.Match[str]) -> str:
        math.append(m.group(m.lastindex or 0))
        return " "

    text = _DISPLAY.sub(keep_math, text)
    for pattern in _DROP:
        text = pattern.sub(" ", text)
    text = _INLINE.sub(keep_math, text)
    for seg in math:
        for pattern in _DROP:
            seg = pattern.sub(" ", seg)
        out += [t for t in _tokens(seg) if not _MATH_OK.fullmatch(t)]
    out += [t for t in _tokens(text) if not any(p.fullmatch(t) for p in allow.patterns)]
    return out


def non_ascii(paths: Iterable[Path]) -> list[str]:
    out = []
    for p in paths:
        for i, line in enumerate(p.read_text(encoding="utf-8").splitlines(), start=1):
            if not line.isascii():
                out.append(f"{p.name}:{i}")
    return out


_SENTENCE: Final = re.compile(r"(?<=[.!?])\s+(?=[A-Z\\])")


def unlabelled_exploratory(tex: str) -> list[str]:
    """Sentences of the exploratory section that cite a number without saying "exploratory" or "post hoc"."""
    text = body(tex)
    out = []
    for para in re.split(r"\n\s*\n", text):
        if "\\begin{figure}" in para:
            continue
        for sentence in _SENTENCE.split(" ".join(para.split())):
            low = sentence.lower()
            if RES.search(sentence) and "exploratory" not in low and "post hoc" not in low:
                out.append(sentence[:100])
    return out


def problems(root: Path) -> list[str]:
    """Every rule the sources break, as messages (empty when all hold)."""
    out: list[str] = []
    reg = load_registry(root)
    sources = tex_sources(root)
    texts = {p: p.read_text(encoding="utf-8") for p in sources}
    used: set[str] = set()
    for p, tex in texts.items():
        names = set(RES.findall(body(tex)))
        used |= names
        for name in sorted(names - set(reg)):
            out.append(f"{p.name}: \\res{{{name}}} is not in {REGISTRY}")
    for name in sorted(set(reg) - used):
        out.append(f"{REGISTRY}: {name} is not used by the text")
    allow = load_allowlist(root)
    for p, tex in texts.items():
        for tok in bare_numbers(tex, allow):
            out.append(
                f"{p.name}: hard-coded number {tok!r} (use \\res or add a design constant to {ALLOWLIST})"
            )
    ascii_files = [
        *sources,
        *sorted((root / PAPER).glob("*.bib")),
        *sorted((root / PAPER).glob("*.yaml")),
        *sorted(p for p in (root / ARXIV).glob("*") if p.suffix in (".txt", ".md", ".tex")),
    ]
    if (root / OUTPUT).is_file():
        ascii_files.append(root / OUTPUT)
    out += [f"non-ASCII line {where}" for where in non_ascii(ascii_files)]
    explo = root / EXPLORATORY_TEX
    if explo.is_file():
        for s in unlabelled_exploratory(explo.read_text(encoding="utf-8")):
            out.append(f"{explo.name}: a sentence cites a number without 'exploratory' or 'post hoc': {s!r}")
    n = words(abstract_text(root))
    if not ABSTRACT_WORDS[0] <= n <= ABSTRACT_WORDS[1]:
        out.append(f"the abstract has {n} words (expected {ABSTRACT_WORDS[0]} to {ABSTRACT_WORDS[1]})")
    return out


# --- command line -------------------------------------------------------------------------------------------


def outputs(root: Path) -> Mapping[str, str]:
    """The generated files and their text."""
    return {OUTPUT: numbers_tex(root), ABSTRACT_TXT: abstract_text(root)}


def main(argv: Sequence[str] | None = None, layout: Layout | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m newsaction.paper.numbers")
    ap.add_argument("--check", action="store_true", help="fail if a generated file is stale; write nothing")
    args = ap.parse_args(argv)
    root = resolve_layout(layout).root
    status = 0
    for rel, text in outputs(root).items():
        path = root / rel
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                print(f"stale: {rel} (run make paper-text)", file=sys.stderr)
                status = 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {rel}")
    found = problems(root)
    for msg in found:
        print(f"problem: {msg}", file=sys.stderr)
    report: dict[str, Any] = {
        "numbers": len(load_registry(root)),
        "abstract_words": words(abstract_text(root)),
        "problems": len(found),
    }
    print(report)
    return 1 if found or status else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
